"""
Streamlit app for the Heart Disease Prediction ML project.

Run with:
    streamlit run app.py

Requires model artifacts in model/ (generated by train_model.py).
"""

import json
import os

import joblib
import pandas as pd
import streamlit as st

# ------------------------------------------------------------------
# Page config
# ------------------------------------------------------------------
st.set_page_config(
    page_title="Heart Disease Risk Predictor",
    page_icon="❤️",
    layout="wide",
)

MODEL_DIR = "model"


# ------------------------------------------------------------------
# Cached loaders
# ------------------------------------------------------------------
@st.cache_resource
def load_artifacts():
    missing = not os.path.exists(os.path.join(MODEL_DIR, "best_model.pkl"))
    if missing:
        return None
    model = joblib.load(os.path.join(MODEL_DIR, "best_model.pkl"))
    scaler = joblib.load(os.path.join(MODEL_DIR, "scaler.pkl"))
    with open(os.path.join(MODEL_DIR, "metadata.json")) as f:
        metadata = json.load(f)
    comparison = pd.read_csv(os.path.join(MODEL_DIR, "comparison_table.csv"), index_col="Model")
    importance = pd.read_csv(os.path.join(MODEL_DIR, "feature_importance.csv"), index_col=0)
    cm = pd.read_csv(os.path.join(MODEL_DIR, "confusion_matrix.csv"), index_col=0)
    return {
        "model": model,
        "scaler": scaler,
        "metadata": metadata,
        "comparison": comparison,
        "importance": importance,
        "cm": cm,
    }


artifacts = load_artifacts()

# ------------------------------------------------------------------
# Header
# ------------------------------------------------------------------
st.title("❤️ Heart Disease Risk Predictor")
st.caption(
    "A machine learning project comparing Logistic Regression, Random Forest, "
    "and KNN on the UCI Heart Disease dataset."
)

if artifacts is None:
    st.error(
        "No trained model found in `model/`. Run `python train_model.py` once "
        "(with `heart.csv` in this folder) to generate the model artifacts, "
        "then reload this app."
    )
    st.stop()

model = artifacts["model"]
scaler = artifacts["scaler"]
metadata = artifacts["metadata"]
comparison = artifacts["comparison"]
importance = artifacts["importance"]
cm = artifacts["cm"]
feature_order = metadata["feature_order"]
best_model_name = metadata["best_model_name"]

tab_predict, tab_insights, tab_about = st.tabs(
    ["🩺 Predict", "📊 Model Insights", "ℹ️ About"]
)

# ------------------------------------------------------------------
# Human-readable option maps for categorical clinical features
# ------------------------------------------------------------------
SEX_OPTIONS = {"Female": 0, "Male": 1}
CP_OPTIONS = {
    "Typical angina": 0,
    "Atypical angina": 1,
    "Non-anginal pain": 2,
    "Asymptomatic": 3,
}
FBS_OPTIONS = {"No (<= 120 mg/dl)": 0, "Yes (> 120 mg/dl)": 1}
RESTECG_OPTIONS = {
    "Normal": 0,
    "ST-T wave abnormality": 1,
    "Left ventricular hypertrophy": 2,
}
EXANG_OPTIONS = {"No": 0, "Yes": 1}
SLOPE_OPTIONS = {"Upsloping": 0, "Flat": 1, "Downsloping": 2}
THAL_OPTIONS = {
    "Normal": 1,
    "Fixed defect": 2,
    "Reversible defect": 3,
    "Unknown": 0,
}

# ------------------------------------------------------------------
# TAB 1: Predict
# ------------------------------------------------------------------
with tab_predict:
    st.subheader("Enter patient clinical data")
    st.write(
        "Fill in the values below and click **Predict** to estimate heart "
        "disease risk using the trained **{}** model.".format(best_model_name)
    )

    col1, col2, col3 = st.columns(3)

    with col1:
        age = st.slider("Age", 18, 100, 54)
        sex_label = st.selectbox("Sex", list(SEX_OPTIONS.keys()))
        cp_label = st.selectbox("Chest pain type", list(CP_OPTIONS.keys()))
        trestbps = st.slider("Resting blood pressure (mm Hg)", 80, 220, 130)
        chol = st.slider("Serum cholesterol (mg/dl)", 100, 600, 246)

    with col2:
        fbs_label = st.selectbox("Fasting blood sugar", list(FBS_OPTIONS.keys()))
        restecg_label = st.selectbox("Resting ECG results", list(RESTECG_OPTIONS.keys()))
        thalach = st.slider("Max heart rate achieved", 60, 220, 150)
        exang_label = st.selectbox("Exercise-induced angina", list(EXANG_OPTIONS.keys()))
        oldpeak = st.slider("ST depression induced by exercise (oldpeak)", 0.0, 7.0, 1.0, 0.1)

    with col3:
        slope_label = st.selectbox("Slope of peak exercise ST segment", list(SLOPE_OPTIONS.keys()))
        ca = st.selectbox("Number of major vessels colored by fluoroscopy (ca)", [0, 1, 2, 3, 4])
        thal_label = st.selectbox("Thalassemia (thal)", list(THAL_OPTIONS.keys()))

    st.divider()
    predict_clicked = st.button("🔍 Predict", type="primary", use_container_width=True)

    if predict_clicked:
        input_dict = {
            "age": age,
            "sex": SEX_OPTIONS[sex_label],
            "cp": CP_OPTIONS[cp_label],
            "trestbps": trestbps,
            "chol": chol,
            "fbs": FBS_OPTIONS[fbs_label],
            "restecg": RESTECG_OPTIONS[restecg_label],
            "thalach": thalach,
            "exang": EXANG_OPTIONS[exang_label],
            "oldpeak": oldpeak,
            "slope": SLOPE_OPTIONS[slope_label],
            "ca": ca,
            "thal": THAL_OPTIONS[thal_label],
        }
        input_df = pd.DataFrame([input_dict])[feature_order]
        input_scaled = scaler.transform(input_df)

        prediction = model.predict(input_scaled)[0]
        proba = model.predict_proba(input_scaled)[0]
        disease_prob = proba[1]

        st.subheader("Result")
        res_col1, res_col2 = st.columns([1, 2])

        with res_col1:
            if prediction == 1:
                st.error(f"⚠️ **Higher likelihood of heart disease**")
            else:
                st.success(f"✅ **Lower likelihood of heart disease**")
            st.metric("Predicted probability of disease", f"{disease_prob:.1%}")

        with res_col2:
            st.progress(min(max(disease_prob, 0.0), 1.0))
            st.caption(
                "This is a probability score from a machine learning model trained on "
                "historical data, not a medical diagnosis. Always consult a qualified "
                "doctor for real clinical decisions."
            )

# ------------------------------------------------------------------
# TAB 2: Model Insights,#c6efce
# ------------------------------------------------------------------

with tab_insights:
    st.subheader("Model Comparison")
    st.dataframe(
        comparison.style.highlight_max(axis=0, color="#c6efce"),
        use_container_width=True,
    )
    st.caption(
        f"**Best model: {best_model_name}** — selected by F1 Score, since in a medical "
        "screening context both false negatives (missed disease) and false positives "
        "(false alarms) matter, and F1 balances precision and recall."
    )

    st.divider()

    ins_col1, ins_col2 = st.columns(2)

    with ins_col1:
        st.markdown("**Metric comparison across models**")
        st.bar_chart(comparison)

    with ins_col2:
        st.markdown("**Feature importance (Random Forest)**")
        st.bar_chart(importance)

    st.divider()
    st.markdown(f"**Confusion Matrix — {best_model_name}**")
    st.dataframe(cm, use_container_width=True)

# ------------------------------------------------------------------
# TAB 3: About
# ------------------------------------------------------------------
with tab_about:
    st.subheader("About this project")
    st.markdown(
        """
This app is a Streamlit front-end for a machine learning project that predicts
the presence of heart disease from 13 clinical features.

**Dataset:** [Heart Disease Dataset — Kaggle](https://www.kaggle.com/datasets/johnsmith88/heart-disease-dataset)
(~1025 patient records after deduplication, UCI Cleveland heart disease data)

**Models compared:** Logistic Regression, Random Forest, K-Nearest Neighbors

**Evaluation metrics:** Accuracy, Precision, Recall, F1 Score

**Pipeline:**
1. Data loading & inspection
2. Cleaning (duplicate removal, type checks)
3. Stratified-aware 80/20 train/test split
4. Feature engineering (correlation heatmap + Random Forest feature importance)
5. Model training (3 algorithms)
6. Evaluation & comparison table
7. Best model selection (by F1 Score) + confusion matrix

**Author:** Aayush Rathod
        """
    )
